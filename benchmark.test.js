import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const b=JSON.parse(fs.readFileSync(new URL('./benchmarks/capacity-engineering-v1.json',import.meta.url)));
const near=(a,b,t=1e-3)=>Math.abs(a-b)<=t;
test('benchmark has exactly 20 unique cases',()=>{assert.equal(b.cases.length,20);assert.equal(new Set(b.cases.map(x=>x.id)).size,20)});
test('CEB1-01 effective capacity',()=>assert.equal(100*.85,85));
test('CEB1-02 OEE',()=>assert.ok(near(.9*.95*.98*100,83.79)));
test('CEB1-03 hours',()=>assert.equal(2*8*5,80));
test('CEB1-04 bottleneck',()=>assert.equal(Math.min(120,90,150),90));
test('CEB1-05 equal load',()=>assert.equal(200/200*100,100));
test('CEB1-06 slack',()=>assert.equal(500-350,150));
test('CEB1-07 denominator trap',()=>{assert.equal((120-100)/100*100,20);assert.ok(near((120-100)/120*100,16.6667,.001));assert.equal(120/100*100,120)});
test('CEB1-08 yield',()=>assert.equal(200*.96,192));
test('CEB1-09 changeover',()=>assert.equal(50*(8-1.5),325));
test('CEB1-10 parallel',()=>assert.equal(40+55+35,130));
test('CEB1-11 mix',()=>{const m=(100*60+80*90)/60;assert.equal(m,220);assert.ok(near(m/480*100,45.8333,.001))});
test('CEB1-12 monthly hourly',()=>assert.equal(17600/22/8,100));
test('CEB1-13 missing data is explicit',()=>assert.equal(b.cases.find(x=>x.id==='CEB1-13').expected.action,'insufficient_data'));
test('CEB1-14 percentage denominators',()=>{assert.equal((100-80)/80*100,25);assert.equal((100-80)/100*100,20)});
test('CEB1-15 OEE insufficiency',()=>{assert.equal(130*.8,104);assert.equal(110-104,6)});
test('CEB1-16 worst year',()=>assert.equal(b.cases.find(x=>x.id==='CEB1-16').expected.worst_year,2027));
test('CEB1-17 routing',()=>{assert.equal(25*4,100);assert.equal(20*4,80)});
test('CEB1-18 crew rate',()=>assert.equal(15*4*8,480));
test('CEB1-19 annual daily',()=>assert.equal(50000/250,200));
test('CEB1-20 combined losses',()=>assert.ok(near(160*7*.9*.97,977.76)));
